"""Detection tests for five more policy gates (bd imperialism-decomp-x1cl).

Same discipline as tests/tools/test_policy_gate_detection.py: positive detection tests,
because the failure this bead is about is a pattern silently ceasing to match while the
gate keeps exiting 0. Negative cases pin only the exclusions that were built in on
purpose.

Takes the covered set from 3 of 18 to 8 of 18.
"""

from __future__ import annotations

import unittest
from pathlib import Path
from tempfile import TemporaryDirectory

from tools.workflow.check_destructor_placement import CPP_DTOR_RE, HDR_DTOR_RE, canonical_addr
from tools.workflow.check_generated_markers import is_genuinely_generated
from tools.workflow.check_global_redeclarations import EXTERN_RE
from tools.workflow.check_manual_cruntimeclass import find_manual_cruntimeclass_definitions
from tools.workflow.check_typedef_cast_drift import TYPEDEF_RE, normalize, strip_param_names


class DestructorPlacementTest(unittest.TestCase):
    def test_addresses_canonicalize_across_padding_and_case(self) -> None:
        # Same class of defect as the marker gate's normalize_offset: every spelling of
        # one address has to collapse to one key, or a placement violation goes unpaired.
        canonical = canonical_addr("0x4dfd30")
        for spelling in ("0x004dfd30", "0x004DFD30", "4dfd30", "  0x4DFD30  "):
            with self.subTest(spelling=spelling):
                self.assertEqual(canonical_addr(spelling), canonical)

    def test_empty_address_stays_empty_rather_than_raising(self) -> None:
        self.assertEqual(canonical_addr(""), "")
        self.assertEqual(canonical_addr("   "), "")

    def test_out_of_line_destructor_definition_is_matched(self) -> None:
        match = CPP_DTOR_RE.match("TCity::~TCity()")
        assert match is not None
        self.assertEqual(match.group("cls"), "TCity")
        self.assertEqual(match.group("name"), "TCity")

    def test_header_destructor_declaration_is_matched(self) -> None:
        for line, name in (
            ("  virtual ~TCity();", "TCity"),
            ("  ~WaveLoadDescriptor() {", "WaveLoadDescriptor"),
        ):
            with self.subTest(line=line):
                match = HDR_DTOR_RE.match(line)
                assert match is not None
                self.assertEqual(match.group("name"), name)


class GeneratedMarkerTest(unittest.TestCase):
    """Hard Rule 7: only files carrying the tool banner are tool output."""

    def test_banner_within_the_scanned_prefix_is_detected(self) -> None:
        lines = ["// AUTO-GENERATED by tools/generate.py", "int x;"]
        self.assertTrue(is_genuinely_generated(lines))

    def test_manual_source_is_not_generated(self) -> None:
        lines = ["// FUNCTION: IMPERIALISM 0x004dfd30", "void TCity::EndCityPhase() {}"]
        self.assertFalse(is_genuinely_generated(lines))

    def test_banner_far_below_the_scanned_prefix_does_not_count(self) -> None:
        # A banner buried deep in a manual file must not launder it into "generated" --
        # that is how a hand-edited file would escape the hand-edit ban.
        lines = ["int x;"] * 500 + ["// AUTO-GENERATED by tools/generate.py"]
        self.assertFalse(is_genuinely_generated(lines))


class GlobalRedeclarationTest(unittest.TestCase):
    """Every global gets exactly one subsystem-header extern; local re-declarations are the defect."""

    def test_plain_extern_is_matched(self) -> None:
        self.assertEqual(EXTERN_RE.findall("extern int g_pSimMgr;\n"), ["g_pSimMgr"])

    def test_pointer_and_const_and_array_forms_are_matched(self) -> None:
        for source, name in (
            ("extern TCity* g_pCity;\n", "g_pCity"),
            ("extern const char* g_szFormat;\n", "g_szFormat"),
            ("extern short g_table[64];\n", "g_table"),
            ('extern "C" int g_flag;\n', "g_flag"),
        ):
            with self.subTest(source=source.strip()):
                self.assertEqual(EXTERN_RE.findall(source), [name])

    def test_a_definition_is_not_an_extern_declaration(self) -> None:
        self.assertEqual(EXTERN_RE.findall("int g_pSimMgr = 0;\n"), [])


class TypedefCastDriftTest(unittest.TestCase):
    def test_function_pointer_typedef_is_matched_with_its_convention(self) -> None:
        match = TYPEDEF_RE.search("typedef void (__thiscall* Restock_t)(void* self);")
        assert match is not None
        self.assertEqual(match.group("conv"), "__thiscall")
        self.assertEqual(match.group("name"), "Restock")

    def test_whitespace_is_normalized(self) -> None:
        self.assertEqual(normalize("  int   *  x \n"), "int * x")

    def test_parameter_names_are_dropped_after_pointer_types(self) -> None:
        self.assertEqual(strip_param_names("TCity* city"), "TCity*")
        self.assertEqual(strip_param_names("int count"), "int")

    def test_short_and_long_parameters_keep_their_names_today(self) -> None:
        """Known limitation, pinned so a future fix is a deliberate change.

        strip_param_names drops a trailing identifier only when the remainder still looks
        like a type, and its exclusion list -- "", const, unsigned, signed, long, short --
        treats `short` and `long` as modifiers that cannot end a type. They are complete
        types on their own, so `short resourceType` keeps its name while `int count` loses
        it, and `unsigned short x` is affected too (the check inspects the last word).

        The consequence is false-positive drift, not missed drift, so it is noise rather
        than a hole in enforcement -- but `short` parameters are everywhere in this
        codebase (tile indices, resource types), so it is worth fixing deliberately rather
        than by accident. Recorded on bd imperialism-decomp-x1cl.
        """
        self.assertEqual(strip_param_names("short resourceType"), "short resourceType")
        self.assertEqual(strip_param_names("unsigned short tileIndex"), "unsigned short tileIndex")

    def test_bare_types_without_names_survive_unchanged(self) -> None:
        # `unsigned` / `short` alone are types, not parameter names -- dropping them would
        # make two different signatures compare equal and hide real drift.
        self.assertEqual(strip_param_names("unsigned int, short"), "unsigned int, short")

    def test_empty_argument_list_is_empty(self) -> None:
        self.assertEqual(strip_param_names(""), "")


class ManualCRuntimeClassTest(unittest.TestCase):
    """MFC RTTI descriptors come from the DECLARE/IMPLEMENT macros, never hand-written."""

    def setUp(self) -> None:
        self._tmp = TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)

    def _write(self, name: str, source: str) -> None:
        (self.root / name).write_text(source, encoding="utf-8")

    def test_hand_written_descriptor_is_flagged(self) -> None:
        self._write("TFoo.cpp", "CRuntimeClass g_rtcTFoo = {nullptr, 0, 0, nullptr, nullptr};\n")
        self.assertTrue(find_manual_cruntimeclass_definitions(self.root))

    def test_macro_generated_source_is_clean(self) -> None:
        self._write("TFoo.cpp", "IMPLEMENT_DYNCREATE(TFoo, CObject)\n")
        self.assertEqual(find_manual_cruntimeclass_definitions(self.root), [])

    def test_the_migration_target_file_is_excluded(self) -> None:
        # global_data_tables.cpp is where these legitimately live during migration.
        self._write(
            "global_data_tables.cpp",
            "CRuntimeClass g_rtcTFoo = {nullptr, 0, 0, nullptr, nullptr};\n",
        )
        self.assertEqual(find_manual_cruntimeclass_definitions(self.root), [])


if __name__ == "__main__":
    unittest.main()
