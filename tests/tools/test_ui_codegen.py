REPO_ROOT = Path(__file__).resolve().parents[2]


class UiCodegenTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.recipes = load_recipes(REPO_ROOT)
        cls.views = load_ui_views(REPO_ROOT)
        cls.text_resources = load_text_resources(REPO_ROOT)
        cls.windows_views = load_windows_views(REPO_ROOT)
        cls.vocabulary_by_event, _ = load_turn_event_vocabulary(REPO_ROOT)
        cls.rendered = {
            recipe.address: render_factory(
                recipe, cls.views, cls.text_resources, cls.windows_views
            )
            for recipe in cls.recipes
        }

    def test_committed_manifest_and_resource_ir_validate(self) -> None:
        self.assertEqual(len(self.recipes), 17)
        self.assertEqual(sum(len(recipe.cases) for recipe in self.recipes), 94)
        self.assertEqual(
            validate(
                REPO_ROOT,
                self.recipes,
                self.views,
                self.text_resources,
                self.windows_views,
            ),
            [],
        )

    def test_generated_claims_replace_manual_factory_ownership(self) -> None:
        model = build_model(REPO_ROOT)
        for recipe in self.recipes:
            claim = model.functions[recipe.address]
            self.assertEqual(claim.origin, "generated")
            self.assertNotIn(recipe.address, model.duplicates)

    def test_resource_emitters_are_deterministic(self) -> None:
        first, second = self.recipes[:2]
        first_text = self.rendered[first.address]
        second_text = self.rendered[second.address]
        self.assertEqual(
            first_text,
            render_factory(first, self.views, self.text_resources, self.windows_views),
        )
        self.assertIn("RegisterUiResourceEntry", first_text)
        self.assertIn("RegisterUiResourceEntry", second_text)

    def test_control_state_uses_recovered_control_api(self) -> None:
        rendered = "\n".join(self.rendered.values())
        self.assertIn("->HiliteState(", rendered)
        self.assertNotIn("SetControlStateFlagAndMaybeRefresh", rendered)
        startup_factory = self.rendered[0x004538A0]
        self.assertIn("node_quer, 0x5b, 8, 0x1a, 0x24, 1, 1,", startup_factory)
        self.assertIn("node_canc, 4, 8, 0x53, 0x24, 1, 1,", startup_factory)

    def test_all_factories_use_the_canonical_semantic_emitter(self) -> None:
        manifest_text = (REPO_ROOT / "config/ui_factory_codegen.yml").read_text()
        self.assertNotIn("emission:", manifest_text)
        self.assertFalse((REPO_ROOT / "config/ui_factory_windows.json").exists())
        for recipe in self.recipes:
            text = self.rendered[recipe.address]
            self.assertTrue(
                text.startswith("// AUTOGENERATED FROM SEMANTIC UI EVIDENCE")
            )
            self.assertIn(
                f"// FUNCTION: IMPERIALISM 0x{recipe.address:08x}", text
            )

    def test_mac_text_and_fixed_point_layout_become_semantics(self) -> None:
        recipe = next(
            recipe for recipe in self.recipes if recipe.address == 0x0043DBC0
        )
        text = self.rendered[recipe.address]
        self.assertIn('BindUiResourceTextAndStyle(0xce4, 4, "Winter, 1888"', text)
        self.assertIn(
            'BindUiResourceTextAndStyle(0x5e5, 2, "Skirmish Report", 3, 4, 0xc, 0, 1)',
            text,
        )
        self.assertIn(
            'BindUiResourceTextAndStyle(0x5e5, 0x12, "One hen,\\rtwo ducks, '
            '\\rthree quacking geese.", 3, 0, 0xc, 0, -2)',
            text,
        )
        self.assertNotIn("SetUiResourceLayoutValues(6, 0, 0x300", text)

    def test_generated_factories_use_recovered_member_names(self) -> None:
        placeholder = re.compile(
            r"->field(?:_|[0-9A-Fa-f])|"
            r"\b(?:Orphan|NoOp|vmethod_|DispatchSlot|CallVoidSlot)[A-Za-z0-9_]*\s*\("
        )
        for recipe in self.recipes:
            text = self.rendered[recipe.address]
            match = placeholder.search(text)
            self.assertIsNone(
                match,
                f"0x{recipe.address:08x} emitted placeholder member {match.group(0)!r}"
                if match
                else "",
            )

    def test_concrete_factory_classes_have_no_placeholder_field_declarations(self) -> None:
        concrete_classes = {
            match.group(1)
            for text in self.rendered.values()
            for match in re.finditer(r"\bnew\s+(T[A-Za-z0-9_]+)\b", text)
        }
        self.assertGreater(len(concrete_classes), 100)

        header_text = {
            path: path.read_text() for path in (REPO_ROOT / "include" / "game").glob("*.h")
        }
        class_owners: dict[str, list[Path]] = {}
        declaration = re.compile(r"\bclass\s+(T[A-Za-z0-9_]+)\b[^;{]*{")
        for path, text in header_text.items():
            for match in declaration.finditer(text):
                class_owners.setdefault(match.group(1), []).append(path)
        placeholder_field = re.compile(
            r"(?m)^\s*(?!//)[^()/;{}]*\b"
            r"(?P<name>(?:field(?:_0x)?[0-9A-Fa-f]+|unknown[A-Za-z0-9_]*))\b"
            r"(?:\s*\[[^\]]+\])?\s*;"
        )
        opaque_pointer_field = re.compile(
            r"(?m)^\s*void\s*\*\s*(?P<name>[A-Za-z_][A-Za-z0-9_]*)"
            r"(?:\s*\[[^\]]+\])?\s*;"
        )

        for class_name in sorted(concrete_classes):
            owners = class_owners.get(class_name, [])
            self.assertEqual(len(owners), 1, f"expected one owning header for {class_name}: {owners}")
            match = placeholder_field.search(header_text[owners[0]])
            self.assertIsNone(
                match,
                f"{class_name} still declares placeholder field {match.group('name')!r} "
                f"in {owners[0].relative_to(REPO_ROOT)}"
                if match
                else "",
            )
            match = opaque_pointer_field.search(header_text[owners[0]])
            self.assertIsNone(
                match,
                f"{class_name} still declares opaque pointer field {match.group('name')!r} "
                f"in {owners[0].relative_to(REPO_ROOT)}"
                if match
                else "",
            )

    def test_generator_foundation_members_have_concrete_types(self) -> None:
        declarations = {
            "TView.h": (
                "bool inputGateFlag4c;",
                "bool childHitTestFlag4d;",
            ),
            "TWindow.h": (
                "bool resourceFlag6c;",
                "bool useCaptionedFrameFlag6d;",
                "bool resourceFlag6e;",
                "bool resourceFlag6f;",
                "bool topmostFlag70;",
                "bool resourceFlag71;",
            ),
            "TEditText.h": (
                "CMcWindow* editWindow;",
                "CFont* editFont;",
                "short maxCharacterCount;",
            ),
            "TPicture.h": ("CDib* cachedBitmap;",),
        }
        for header, expected in declarations.items():
            text = (REPO_ROOT / "include" / "game" / header).read_text()
            for declaration in expected:
                self.assertIn(declaration, text)
            self.assertNotRegex(
                text,
                r"void\s*\*\s*(?:editWindow|editFont|cachedBitmap)\b",
            )

    def test_typed_ir_carries_nested_number_and_command_values(self) -> None:
        view = self.views[next(key for key in self.views if key.text() == "MapView.rsrc:2013")]
        defend = next(node for node in view["nodes"] if node["tag"] == "dfnd")
        self.assertEqual(defend["control_value"], 0x41D)

        number_view = next(
            view
            for view in self.views.values()
            if any(node["type_code"] == "nmbr" for node in view["nodes"])
        )
        number = next(node for node in number_view["nodes"] if node["type_code"] == "nmbr")
        self.assertIn("max_char_count", number["family"])
        self.assertIn("number_minimum", number["family"])
        self.assertIn("number_maximum", number["family"])

    def test_windows_only_event_emits_a_semantic_tree(self) -> None:
        view = self.windows_views["join_selector_message"]
        self.assertEqual(view.event, 0x05E7)
        self.assertEqual(len(view.nodes), 12)
        self.assertEqual(sum(node.parent_id is None for node in view.nodes), 1)

        recipe = next(recipe for recipe in self.recipes if recipe.address == 0x0044AF90)
        text = self.rendered[recipe.address]
        case_text = text[text.index("case kTurnEventJoinSelectorMessage:") :]
        self.assertIn("new TFloatWindow()", case_text)
        self.assertIn("new TMultiMessagePicture()", case_text)
        self.assertEqual(case_text.count("new TCzechBox()"), 7)
        self.assertIn("evidence 0x0044e466", case_text)

    def test_functional_parity_cases_emit_nonempty_mac_trees_with_provenance(self) -> None:
        expected = {
            0x07E5: "Windows request 0x005d57ce",
            0x03C5: "Windows request 0x0051dd0b",
            0x0F3D: "Windows request 0x0057e984",
        }
        cases = {
            case.event: (recipe, case)
            for recipe in self.recipes
            for case in recipe.cases
            if case.event in expected
        }

        self.assertEqual(set(cases), set(expected))
        for event, evidence in expected.items():
            recipe, case = cases[event]
            self.assertIsNotNone(case.resource)
            self.assertIn(evidence, case.evidence)
            text = self.rendered[recipe.address]
            case_text = text[text.index(f"case {self.vocabulary_by_event[event]}:") :]
            self.assertIn("// FUNCTIONAL_PARITY:", case_text)
            self.assertIn("RegisterUiResourceEntry", case_text)
        self.assertNotIn("WINDOWS_ONLY", case_text)
        windows_view_text = (
            REPO_ROOT / "config/ui_factory_windows_views.yml"
        ).read_text()
        for implementation_field in (
            "allocation:",
            "emission:",
            "clear:",
            "pops:",
            "variable:",
        ):
            self.assertNotIn(implementation_field, windows_view_text)

    def test_writing_same_inputs_does_not_touch_outputs(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            write_generated(
                REPO_ROOT,
                output,
                self.recipes,
                self.views,
                self.text_resources,
                self.windows_views,
            )
            before = {
                path.name: (path.read_bytes(), path.stat().st_mtime_ns)
                for path in output.iterdir()
            }
            write_generated(
                REPO_ROOT,
                output,
                self.recipes,
                self.views,
                self.text_resources,
                self.windows_views,
            )
            after = {
                path.name: (path.read_bytes(), path.stat().st_mtime_ns)
                for path in output.iterdir()
            }
            self.assertEqual(before, after)

    def test_source_map_covers_every_emitted_case_and_node(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            write_generated(
                REPO_ROOT,
                output,
                self.recipes,
                self.views,
                self.text_resources,
                self.windows_views,
            )
            source_map = json.loads((output / "_source_map.json").read_text())
            case_count = 0
            node_count = 0
            for recipe in self.recipes:
                function = source_map["functions"][f"0x{recipe.address:08x}"]
                generated_lines = (output / function["generated_file"]).read_text().splitlines()
                self.assertEqual(len(function["cases"]), len(recipe.cases))
                case_count += len(function["cases"])
                for case in function["cases"].values():
                    self.assertGreater(len(case["nodes"]), 0)
                    for node in case["nodes"].values():
                        start, end = node["generated_lines"]
                        self.assertGreaterEqual(start, 1)
                        self.assertLessEqual(end, len(generated_lines))
                        self.assertIn(node["source"], generated_lines[start])
                        node_count += 1
            self.assertEqual(case_count, 94)
            self.assertGreater(node_count, 1700)


class UiCodegenMatchingGateTests(unittest.TestCase):
    def test_accepts_equal_or_improved_scores(self) -> None:
        self.assertEqual(
            ui_codegen_regressions(
                [0x401000, 0x402000],
                {"0x401000": {"m": 0.5}, "0x402000": {"m": 0.8}},
                {"0x401000": {"m": 0.5}, "0x402000": {"m": 0.7}},
            ),
            [],
        )

    def test_rejects_regression_and_missing_pair(self) -> None:
        errors = ui_codegen_regressions(
            [0x401000, 0x402000],
            {"0x401000": {"m": 0.4}},
            {"0x401000": {"m": 0.5}, "0x402000": {"m": 0.7}},
        )
        self.assertIn("similarity regressed", errors[0])
        self.assertIn("not paired", errors[1])


