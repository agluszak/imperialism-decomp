from __future__ import annotations

import re
import tempfile
import unittest
from pathlib import Path

from tools.source_model import build_model
from tools.ui_codegen import (
    load_recipes,
    load_ui_views,
    load_windows_recipes,
    render_factory,
    render_resource_recipe,
    validate,
    write_generated,
)
from tools.workflow.check_ui_codegen_matching import check_scores


REPO_ROOT = Path(__file__).resolve().parents[2]


class UiCodegenTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.recipes = load_recipes(REPO_ROOT)
        cls.views = load_ui_views(REPO_ROOT)
        cls.windows_recipes = load_windows_recipes(REPO_ROOT)

    def test_committed_manifest_and_resource_ir_validate(self) -> None:
        self.assertEqual(len(self.recipes), 17)
        self.assertEqual(sum(len(recipe.cases) for recipe in self.recipes), 82)
        self.assertEqual(
            validate(REPO_ROOT, self.recipes, self.views, self.windows_recipes), []
        )

    def test_generated_claims_replace_manual_factory_ownership(self) -> None:
        model = build_model(REPO_ROOT)
        for recipe in self.recipes:
            claim = model.functions[recipe.address]
            self.assertEqual(claim.origin, "generated")
            self.assertNotIn(recipe.address, model.duplicates)

    def test_resource_emitters_are_deterministic(self) -> None:
        expanded = next(
            recipe for recipe in self.recipes if recipe.emission == "expanded"
        )
        compact = next(recipe for recipe in self.recipes if recipe.emission == "compact")
        expanded_text = render_factory(expanded, self.views)
        compact_text = render_factory(compact, self.views)
        self.assertEqual(expanded_text, render_factory(expanded, self.views))
        self.assertIn("InitializeUiResourceEntryFrameAndParent", expanded_text)
        self.assertIn("RegisterUiResourceEntry", compact_text)

    def test_windows_recipes_are_structured_generated_inputs(self) -> None:
        recipe = next(
            recipe for recipe in self.recipes if recipe.emission == "resource_recipe"
        )
        text = render_resource_recipe(
            recipe, self.views, self.windows_recipes
        )
        self.assertTrue(
            text.startswith("// AUTOGENERATED FROM RESOURCE AND WINDOWS RECIPES")
        )
        self.assertIn(f"// FUNCTION: IMPERIALISM 0x{recipe.address:08x}", text)

    def test_generated_factories_use_recovered_member_names(self) -> None:
        placeholder = re.compile(
            r"->field(?:_|[0-9A-Fa-f])|"
            r"\b(?:Orphan|NoOp|vmethod_|DispatchSlot|CallVoidSlot)[A-Za-z0-9_]*\s*\("
        )
        for recipe in self.recipes:
            if recipe.emission == "resource_recipe":
                text = render_resource_recipe(
                    recipe, self.views, self.windows_recipes
                )
            else:
                text = render_factory(recipe, self.views)
            match = placeholder.search(text)
            self.assertIsNone(
                match,
                f"0x{recipe.address:08x} emitted placeholder member {match.group(0)!r}"
                if match
                else "",
            )

    def test_generator_foundation_members_have_concrete_types(self) -> None:
        declarations = {
            "TView.h": (
                "bool inputGateFlag4c;",
                "bool childHitTestFlag4d;",
            ),
            "TWindow.h": (
                "bool resourceFlag6c;",
                "bool useCaptionedFrameFlag6d;",
                "bool resourceFlag6e;",
                "bool resourceFlag6f;",
                "bool topmostFlag70;",
                "bool resourceFlag71;",
            ),
            "TEditText.h": (
                "CMcWindow* editWindow;",
                "CFont* editFont;",
                "short maxCharacterCount;",
            ),
            "TPicture.h": ("CDib* cachedBitmap;",),
        }
        for header, expected in declarations.items():
            text = (REPO_ROOT / "include" / "game" / header).read_text()
            for declaration in expected:
                self.assertIn(declaration, text)
            self.assertNotRegex(
                text,
                r"void\s*\*\s*(?:editWindow|editFont|cachedBitmap)\b",
            )

    def test_typed_ir_carries_nested_number_and_command_values(self) -> None:
        view = self.views[next(key for key in self.views if key.text() == "MapView.rsrc:2013")]
        defend = next(node for node in view["nodes"] if node["tag"] == "dfnd")
        self.assertEqual(defend["control_value"], 0x41D)

        number_view = next(
            view
            for view in self.views.values()
            if any(node["type_code"] == "nmbr" for node in view["nodes"])
        )
        number = next(node for node in number_view["nodes"] if node["type_code"] == "nmbr")
        self.assertIn("max_char_count", number["family"])
        self.assertIn("number_minimum", number["family"])
        self.assertIn("number_maximum", number["family"])

    def test_writing_same_inputs_does_not_touch_outputs(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            write_generated(
                REPO_ROOT,
                output,
                self.recipes,
                self.views,
                self.windows_recipes,
            )
            before = {
                path.name: (path.read_bytes(), path.stat().st_mtime_ns)
                for path in output.iterdir()
            }
            write_generated(
                REPO_ROOT,
                output,
                self.recipes,
                self.views,
                self.windows_recipes,
            )
            after = {
                path.name: (path.read_bytes(), path.stat().st_mtime_ns)
                for path in output.iterdir()
            }
            self.assertEqual(before, after)


class UiCodegenMatchingGateTests(unittest.TestCase):
    def test_accepts_equal_or_improved_scores(self) -> None:
        self.assertEqual(
            check_scores([0x401000, 0x402000], {0x401000: 0.5, 0x402000: 0.8},
                         {0x401000: 0.5, 0x402000: 0.7}),
            [],
        )

    def test_rejects_regression_and_missing_pair(self) -> None:
        errors = check_scores(
            [0x401000, 0x402000], {0x401000: 0.4}, {0x401000: 0.5, 0x402000: 0.7}
        )
        self.assertIn("similarity regressed", errors[0])
        self.assertIn("not paired", errors[1])


if __name__ == "__main__":
    unittest.main()
