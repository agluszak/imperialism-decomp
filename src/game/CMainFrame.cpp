// Overrides CWnd::WinHelp (vtable slot 0x74). The game repurposes F1/help: rather than
// launching WinHelp, post a WM_KEYDOWN VK_F1 to the main include-view host window so the
// keystroke is routed into the active TView tree like any other key. Ignores dwData/nCmd.
// FUNCTION: IMPERIALISM 0x00485c20
