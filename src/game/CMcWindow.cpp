// Overrides CWnd::PreCreateWindow (vtable slot 0x64): register a private "AmbitMcWindow"
// window class (3 = CS_HREDRAW|CS_VREDRAW, DefWindowProc, module instance) and force
// cs.lpszClass before delegating to CWnd::PreCreateWindow.
// FUNCTION: IMPERIALISM 0x00493d80
BOOL CMcWindow::PreCreateWindow(CREATESTRUCT& cs) {
  WNDCLASS wndClass;
  memset(&wndClass, 0, sizeof(wndClass));
  wndClass.lpfnWndProc = ::DefWindowProc;
  wndClass.hInstance = AfxGetInstanceHandle();
  wndClass.style = CS_VREDRAW | CS_HREDRAW;
  wndClass.lpszClassName = "AmbitMcWindow";
  AfxRegisterClass(&wndClass);
  cs.lpszClass = "AmbitMcWindow";
  return CWnd::PreCreateWindow(cs);
}
