from __future__ import annotations

import unittest
from pathlib import Path

from tools.ui_rust_codegen import RUST_OUT, generate, is_current

REPO_ROOT = Path(__file__).resolve().parents[2]


class UiRustCodegenTests(unittest.TestCase):
    def test_all_scenes_generate_without_error(self) -> None:
        output, scenes = generate(REPO_ROOT)
        self.assertGreater(len(scenes), 0)
        self.assertIn("pub fn ", output)

    def test_generated_output_is_current(self) -> None:
        self.assertTrue(is_current(REPO_ROOT))

    def test_generated_banner(self) -> None:
        output, _ = generate(REPO_ROOT)
        self.assertIn("@generated by tools.ui_rust_codegen", output)
        committed = (REPO_ROOT / RUST_OUT).read_text(encoding="utf-8")
        self.assertEqual(output, committed)


if __name__ == "__main__":
    unittest.main()
