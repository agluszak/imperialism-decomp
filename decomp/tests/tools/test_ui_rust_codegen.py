from __future__ import annotations

import unittest
from pathlib import Path

from tools.ui_rust_codegen import (
    RUST_OUT,
    class_has_renderer,
    encountered_classes,
    is_current,
    render,
    resolve_scenes,
)

REPO_ROOT = Path(__file__).resolve().parents[2]


class UiRustCodegenTests(unittest.TestCase):
    def test_all_scenes_generate_without_error(self) -> None:
        scenes = resolve_scenes(REPO_ROOT)
        self.assertGreater(len(scenes), 0)
        output = render(REPO_ROOT)
        self.assertIn("pub fn ", output)
        for fn, _view, roots in scenes:
            self.assertEqual(len(roots), 1)

    def test_generated_output_is_current(self) -> None:
        self.assertTrue(is_current(REPO_ROOT))

    def test_every_encountered_class_has_renderer(self) -> None:
        classes = encountered_classes(REPO_ROOT)
        type_codes = {
            node.class_name: node.type_code
            for _, _, roots in resolve_scenes(REPO_ROOT)
            for node in _walk(roots)
        }
        for class_name in classes:
            type_code = type_codes[class_name]
            self.assertTrue(
                class_has_renderer(class_name, type_code),
                f"{class_name} ({type_code}) lacks a renderer",
            )

    def test_generated_banner(self) -> None:
        rendered = render(REPO_ROOT)
        self.assertIn("@generated by tools.ui_rust_codegen", rendered)
        committed = (REPO_ROOT / RUST_OUT).read_text(encoding="utf-8")
        self.assertEqual(rendered, committed)


def _walk(roots):
    stack = list(roots)
    while stack:
        node = stack.pop()
        yield node
        stack.extend(node.children)
