// FUNCTION: IMPERIALISM 0x00493760
CMcWindow::~CMcWindow() {
  if (m_pOwnerWindow != NULL) {
    m_pOwnerWindow->CloseAndFree();
  }
}

// GetMessageMap (vtable slot 0x30) is compiler-generated by the message-map macros below.

// FUNCTION: IMPERIALISM 0x00493800
LRESULT CMcWindow::OnWindowStateMsg468(WPARAM wParam, LPARAM lParam) {
  switch (wParam & 0xff) {
  case 0:
  case 1:
    break;
  case 2:
    ShowWindow(SW_SHOW);
    break;
  case 3:
    ShowWindow(SW_HIDE);
    break;
  case 4:
    DestroyWindow();
    m_pOwnerWindow = NULL;
    delete this;
    break;
  default:
    if (g_nMcWindowStateMsgAssertGate == 0) {
      ReportAssertionFailure(g_szMcWindowSourcePath, 0xb8);
    }
    break;
  }
  return 0;
}

// FUNCTION: IMPERIALISM 0x004938c0
void CMcWindow::OnPaint() {
  CPaintDC dc(this);
  RECT clipBox;
  dc.GetClipBox(&clipBox);
  if (m_pOwnerWindow != NULL) {
    RECT paintRect;
    CopyRect(&paintRect, &clipBox);
    m_pOwnerWindow->PaintVisibleChildrenIntersectingClipRect(&paintRect, &dc);
  }
}

