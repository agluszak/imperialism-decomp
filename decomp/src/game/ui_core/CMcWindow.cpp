// FUNCTION: IMPERIALISM 0x00493470
CMcWindow::CMcWindow(TWindow* descriptor) : CWnd() {
  m_pOwnerWindow = descriptor;

  DWORD dwExStyle = 0;
  DWORD dwStyle = (descriptor->windowStyleType != 0) ? 0x44020000 : 0x44000000;
  int typeCode = static_cast<int>(descriptor->windowStyleType) & ~0x8;
  switch (typeCode) {
  case 0x00:
    dwStyle |= 0x00fc0000;
    dwExStyle = 0x80;
    break;
  case 0x01:
    dwStyle |= 0x00400000;
    break;
  case 0x02:
    break;
  case 0x03:
    dwStyle |= 0x00800000;
    break;
  case 0x04:
    dwStyle |= 0x00c80000;
    dwExStyle = 0x80;
    break;
  case 0x05:
    dwStyle |= 0x00cc0000;
    break;
  case 0x30:
  case 0x1f40:
    dwExStyle = 0x80;
    if (!descriptor->useCaptionedFrameFlag) {
      dwStyle |= 0x80c00000;
    } else {
      dwStyle |= 0x00c80000;
    }
    break;
  default:
    break;
  }
  if (descriptor->topmostFlag) {
    dwExStyle |= 0x8; // WS_EX_TOPMOST
  }

  CRect rect;
  rect.left = descriptor->ownerLocalX;
  rect.top = descriptor->ownerLocalY;
  rect.right = rect.left + descriptor->frameWidth;
  rect.bottom = rect.top + descriptor->frameHeight;

  CIncludeView* gameView = GetMainViewHostFromActiveThread();
  WINDOWPLACEMENT gameViewPlacement;
  gameView->GetWindowPlacement(&gameViewPlacement);
  OffsetRect(&rect, gameViewPlacement.rcNormalPosition.left,
             gameViewPlacement.rcNormalPosition.top);
  ::AdjustWindowRectEx(&rect, dwStyle, FALSE, dwExStyle);

  CWnd* mainWnd = AfxGetMainWnd();
  HWND parent = (mainWnd != NULL) ? mainWnd->m_hWnd : NULL;
  CreateEx(dwExStyle, NULL, NULL, dwStyle, rect.left, rect.top, rect.Width(), rect.Height(), parent,
           NULL, NULL);
  SetWindowPos(&CWnd::wndTop, 0, 0, 0, 0, SWP_NOMOVE | SWP_NOSIZE);
  BringWindowToTop();
}

