#!/usr/bin/env python3
"""Account for every committed Mac View resource in the Windows source model.

The turn-event UI manifest owns resources that are already generated.  The
coverage classification file owns only the complement: resources that still
need Windows recovery or have evidence for exclusion.  Normal checks consume
committed evidence only; they never read either retail binary.
"""

from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

import yaml

from tools.common.repo import repo_root_from_file
from tools.ui_codegen import UiResourceKey, load_recipes, load_ui_views


CLASSIFICATION_PATH = "config/ui_view_coverage.yml"
MANIFEST_PATH = "config/ui_factory_codegen.yml"
REPORT_PATH = "docs/reference/ui_view_coverage.md"
FORMAT_VERSION = 1
ALLOWED_STATUSES = frozenset(
    (
        "windows_runtime_gap",
        "needs_windows_classification",
        "excluded_mac_test_debug_or_framework",
        "windows_alternate_path",
    )
)


@dataclass(frozen=True)
class CoverageClassification:
    key: UiResourceKey
    status: str
    name: str
    reason: str
    evidence: tuple[str, ...]
    bead: str


@dataclass(frozen=True)
class CoverageRow:
    key: UiResourceKey
    name: str
    node_count: int
    status: str
    owner: str
    evidence: tuple[str, ...]
    bead: str


def _mapping(value: object, context: str) -> dict:
    if not isinstance(value, dict):
        raise ValueError(f"{context}: expected an object")
    return value


def load_classifications(repo_root: Path) -> dict[UiResourceKey, CoverageClassification]:
    path = repo_root / CLASSIFICATION_PATH
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if data.get("format_version") != FORMAT_VERSION:
        raise ValueError(
            f"{CLASSIFICATION_PATH}: unsupported format_version "
            f"{data.get('format_version')!r}"
        )
    rows = _mapping(data.get("resources"), f"{CLASSIFICATION_PATH}: resources")
    classifications: dict[UiResourceKey, CoverageClassification] = {}
    for raw_key, raw_value in rows.items():
        key = UiResourceKey.parse(str(raw_key))
        context = f"{CLASSIFICATION_PATH}: {key.text()}"
        row = _mapping(raw_value, context)
        unknown = sorted(set(row) - {"status", "name", "reason", "evidence", "bead"})
        if unknown:
            raise ValueError(f"{context}: unknown fields {', '.join(unknown)}")
        status = str(row.get("status", ""))
        if status not in ALLOWED_STATUSES:
            raise ValueError(f"{context}: invalid status {status!r}")
        evidence_value = row.get("evidence")
        if not isinstance(evidence_value, list) or not evidence_value:
            raise ValueError(f"{context}: evidence must be a non-empty list")
        evidence = tuple(str(value).strip() for value in evidence_value)
        if any(not value for value in evidence):
            raise ValueError(f"{context}: evidence entries must be non-empty")
        classification = CoverageClassification(
            key=key,
            status=status,
            name=str(row.get("name", "")).strip(),
            reason=str(row.get("reason", "")).strip(),
            evidence=evidence,
            bead=str(row.get("bead", "")).strip(),
        )
        if not classification.name or not classification.reason or not classification.bead:
            raise ValueError(f"{context}: name, reason, and bead are required")
        if key in classifications:
            raise ValueError(f"{context}: duplicate resource")
        classifications[key] = classification
    return classifications


def build_coverage_rows(repo_root: Path) -> tuple[list[CoverageRow], list[str]]:
    recipes = load_recipes(repo_root)
    views = load_ui_views(repo_root)
    classifications = load_classifications(repo_root)
    generated: dict[UiResourceKey, tuple[int, int, str]] = {}
    errors: list[str] = []

    for recipe in recipes:
        for case in recipe.cases:
            if case.resource is None:
                continue
            if case.resource in generated:
                previous = generated[case.resource]
                errors.append(
                    f"{case.resource.text()}: generated by both 0x{previous[0]:08x}/"
                    f"0x{previous[1]:04x} and 0x{recipe.address:08x}/0x{case.event:04x}"
                )
            generated[case.resource] = (recipe.address, case.event, case.evidence)

    for key, classification in classifications.items():
        view = views.get(key)
        if view is None:
            errors.append(f"{key.text()}: classification has no committed Mac View")
            continue
        if key in generated:
            errors.append(f"{key.text()}: generated resource must not be classified manually")
        actual_name = str(view.get("view_name", ""))
        if classification.name != actual_name:
            errors.append(
                f"{key.text()}: classification name {classification.name!r} does not match "
                f"committed name {actual_name!r}"
            )

    missing = sorted(set(views) - set(generated) - set(classifications), key=lambda key: key.text())
    for key in missing:
        errors.append(f"{key.text()}: unclassified committed Mac View")
    extra = sorted(set(classifications) - set(views), key=lambda key: key.text())
    for key in extra:
        errors.append(f"{key.text()}: classification is not present in committed Mac View IR")

    rows: list[CoverageRow] = []
    for key, view in sorted(views.items(), key=lambda item: (item[0].resource_file, item[0].view_id)):
        name = str(view.get("view_name", ""))
        node_count = len(view.get("nodes", []))
        if key in generated:
            address, event, evidence = generated[key]
            rows.append(
                CoverageRow(
                    key,
                    name,
                    node_count,
                    "generated_turn_event_factory",
                    f"0x{address:08x}/event 0x{event:04x}",
                    (evidence or f"{key.text()} in {MANIFEST_PATH}",),
                    (
                        "imperialism-decomp-1uj.58.7.1"
                        if evidence
                        else "imperialism-decomp-1uj.51.12"
                    ),
                )
            )
            continue
        classification = classifications.get(key)
        if classification is None:
            continue
        rows.append(
            CoverageRow(
                key,
                name,
                node_count,
                classification.status,
                classification.reason,
                classification.evidence,
                classification.bead,
            )
        )

    if len(rows) != len(views):
        errors.append(f"coverage has {len(rows)} rows for {len(views)} committed Mac Views")
    return rows, sorted(set(errors))


def render_report(rows: list[CoverageRow]) -> str:
    counts = Counter(row.status for row in rows)
    lines = [
        "<!-- AUTO-GENERATED by tools/workflow/ui_view_coverage.py; DO NOT EDIT. -->",
        "# Mac View coverage in the Windows source model",
        "",
        "This report accounts for every committed Mac `View` resource. Generated rows are",
        "derived from `config/ui_factory_codegen.yml`; all other rows require explicit",
        "classification and evidence in `config/ui_view_coverage.yml`. Retail binaries are",
        "not inputs to this check.",
        "",
        "## Summary",
        "",
        f"- Total committed Mac views: {len(rows)}",
    ]
    for status in sorted(counts):
        lines.append(f"- `{status}`: {counts[status]}")
    lines.extend(
        (
            "",
            "## Resources",
            "",
            "| Resource | Name | Nodes | Status | Owner or disposition | Evidence | Bead |",
            "| --- | --- | ---: | --- | --- | --- | --- |",
        )
    )
    for row in rows:
        evidence = "<br>".join(value.replace("|", "\\|") for value in row.evidence)
        owner = row.owner.replace("|", "\\|")
        name = row.name.replace("|", "\\|")
        lines.append(
            f"| `{row.key.text()}` | {name} | {row.node_count} | `{row.status}` | "
            f"{owner} | {evidence} | `{row.bead}` |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--check", action="store_true", help="fail if the report is stale")
    action.add_argument("--write", action="store_true", help="rewrite the committed report")
    args = parser.parse_args()
    repo_root = repo_root_from_file(__file__, levels_up=2)
    try:
        rows, errors = build_coverage_rows(repo_root)
    except (KeyError, TypeError, ValueError) as exc:
        print(f"UI View coverage failed: {exc}")
        return 1
    if errors:
        print("UI View coverage failed:")
        for error in errors:
            print(f"  - {error}")
        return 1

    report = render_report(rows)
    report_path = repo_root / REPORT_PATH
    if args.write:
        report_path.write_text(report, encoding="utf-8")
        print(f"Wrote {REPORT_PATH}: {len(rows)} views")
        return 0
    if args.check:
        current = report_path.read_text(encoding="utf-8") if report_path.is_file() else ""
        if current != report:
            print(f"UI View coverage failed: {REPORT_PATH} is stale; run with --write")
            return 1
        counts = Counter(row.status for row in rows)
        summary = ", ".join(f"{status}={counts[status]}" for status in sorted(counts))
        print(f"UI View coverage passed: {len(rows)} views ({summary})")
        return 0
    print(report, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
