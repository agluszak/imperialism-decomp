#!/usr/bin/env python3
"""Gate against stale "generated declaration" ownership markers in manual source.

Every file under ``include/game`` and ``src/game`` is manually owned source. The
retired ``recover-class`` codegen used to stamp headers with a
``// === BEGIN GENERATED DECLS (Class) — refreshed by recover-class; do not
hand-edit ===`` … ``// === END GENERATED DECLS (Class) ===`` boundary and claim the
declarations inside it as tool-owned. That workflow no longer exists: declarations
are authored and edited by hand and verified with ``just build`` / ``just vtable`` /
``just gates``. The read-only vtable/RTTI extractor (``just class-vtable-dump``) may
inspect these files but must never rewrite them.

This gate fails if any of the obsolete marker strings reappear in a manual source
file, so the false "do not hand-edit" boundaries cannot creep back in. It never
scans the genuinely generated trees (``include/ghidra_autogen``, ``src/autogen``,
``src/ghidra_autogen``), which are legitimately tool-owned.

Check-only; it never edits files.
"""

from __future__ import annotations

import argparse

from tools.common.file_scan import iter_files
from tools.common.repo import normalize_repo_relative_path, repo_root_from_file

# Substrings that only ever came from the retired recover-class source generator.
BANNED_SUBSTRINGS = (
    "BEGIN GENERATED DECLS",
    "END GENERATED DECLS",
    "refreshed by recover-class",
    "do not hand-edit",
)

# A genuine machine-generated file (e.g. src/game/library_msvc500_oracle.cpp, produced
# by the retired oracle applier) legitimately carried a "do not hand-edit" banner.
# Those are tool-owned by an *active* workflow, unlike the retired recover-class DECLS
# claim stamped on hand-owned headers, so exempt any file that opens with a real
# auto-generation banner.
GENERATED_BANNER = "AUTO-GENERATED by tools/"
BANNER_SCAN_LINES = 3


def is_genuinely_generated(lines: list[str]) -> bool:
    return any(GENERATED_BANNER in line for line in lines[:BANNER_SCAN_LINES])

# Manual, hand-owned source roots. The generated trees are deliberately excluded --
# their tool-ownership is real, not a stale claim.
DEFAULT_PATHS = ("include/game", "src/game")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--paths",
        nargs="+",
        default=list(DEFAULT_PATHS),
        help="Files or directories of manual source to scan.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    repo_root = repo_root_from_file(__file__)

    violations: list[str] = []
    scanned = 0
    for path in iter_files(args.paths):
        scanned += 1
        rel = normalize_repo_relative_path(path, repo_root)
        lines = path.read_text(encoding="utf-8", errors="ignore").splitlines()
        if is_genuinely_generated(lines):
            continue
        for idx, line in enumerate(lines):
            for needle in BANNED_SUBSTRINGS:
                if needle in line:
                    violations.append(f"{rel}:{idx + 1}: stale recover-class marker: {needle!r}")

    if not violations:
        print(f"Generated-marker gate passed ({scanned} manual source files scanned).")
        return 0

    print("Generated-marker gate failed: manual source is hand-owned, not generated.")
    print("Remove the marker boundary; the declarations stay, only the false claim goes.")
    for item in sorted(violations):
        print(f"    - {item}")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
