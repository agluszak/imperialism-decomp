"""Generate the C++ native runtime registry from tools.runtime.catalog."""

from __future__ import annotations

import argparse
from pathlib import Path

from tools.runtime.catalog import TESTS


def render_registry() -> str:
    def snapshot_flags(snapshots: tuple[str, ...]) -> str:
        flags = []
        if "ui" in snapshots:
            flags.append("kRuntimeSnapshotUi")
        if "map" in snapshots:
            flags.append("kRuntimeSnapshotMap")
        return " | ".join(flags) or "kRuntimeSnapshotNone"

    rows = "\n".join(
        f'    {{"{test.name}", {test.native_factory}(), '
        f'{snapshot_flags(test.native_snapshots)}, "{test.evidence_kind}"}},'
        for test in TESTS
        if test.execution == "game"
    )
    return (
        "// AUTO-GENERATED by tools/runtime/generate_native_registry.py; do not edit.\n"
        "RuntimeTestDescriptor g_descriptors[] = {\n"
        f"{rows}\n"
        "};\n"
    )


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    write_if_changed(args.output, render_registry())
    game_tests = sum(test.execution == "game" for test in TESTS)
    print(f"Wrote {args.output} ({game_tests} native runtime descriptors)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
