"""Generate the C++ native runtime registry and factory declarations from tools.runtime.catalog.

Two includes come out of here, both from the same `native_factory` field, so the catalog is
the single source of truth for a test's registered name:

  RuntimeRegistry.inc            the descriptor array
  RuntimeScenarioFactories.inc   one `RuntimeTestCase* Name();` per test

The declarations used to live in a hand-maintained scenarios/RuntimeScenarios.h whose only
tie to the catalog was convention -- nothing verified the pairing except the link step, so a
mismatch surfaced as an unresolved symbol rather than as a naming error. Generating both from
one list removes that failure mode.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from tools.runtime.catalog import TESTS


BANNER = "// AUTO-GENERATED by tools/runtime/generate_native_registry.py; do not edit.\n"


def _game_tests():
    # `execution="harness"` entries are a separate executable with its own main(), so they have
    # no descriptor and no factory in this binary.
    return [test for test in TESTS if test.execution == "game"]


def render_registry() -> str:
    def snapshot_flags(snapshots: tuple[str, ...]) -> str:
        flags = []
        if "ui" in snapshots:
            flags.append("kRuntimeSnapshotUi")
        if "map" in snapshots:
            flags.append("kRuntimeSnapshotMap")
        return " | ".join(flags) or "kRuntimeSnapshotNone"

    rows = "\n".join(
        f'    {{"{test.name}", {test.native_factory}(), '
        f'{snapshot_flags(test.native_snapshots)}, "{test.evidence_kind}"}},'
        for test in _game_tests()
    )
    return BANNER + "RuntimeTestDescriptor g_descriptors[] = {\n" + rows + "\n};\n"


def render_factories() -> str:
    """Declarations for every factory the descriptor array references.

    UnknownRuntimeTest is not a catalog entry -- the harness falls back to it when an
    unrecognised test name is requested -- so it is declared explicitly.
    """
    names = sorted({test.native_factory for test in _game_tests()} | {"UnknownRuntimeTest"})
    lines = "\n".join(f"RuntimeTestCase* {name}();" for name in names)
    return (
        BANNER
        + "// Defined by RUNTIME_TEST_FACTORY at the bottom of each scenario translation unit.\n"
        + "class RuntimeTestCase;\n"
        + lines
        + "\n"
    )


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="RuntimeRegistry.inc path")
    parser.add_argument(
        "--factories-output",
        type=Path,
        help="RuntimeScenarioFactories.inc path (default: alongside --output)",
    )
    args = parser.parse_args()
    write_if_changed(args.output, render_registry())
    factories = args.factories_output or args.output.with_name("RuntimeScenarioFactories.inc")
    write_if_changed(factories, render_factories())
    print(
        f"Wrote {args.output} and {factories} "
        f"({len(_game_tests())} native runtime descriptors)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
