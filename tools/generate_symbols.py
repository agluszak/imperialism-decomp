#!/usr/bin/env python3
"""Generate the reccmp symbols table: raw inventory + source-derived overlay.

`config/original_entities.csv` is the committed raw original-binary inventory
(addresses, kinds, sizes, advisory names/prototypes from analysis). It is never
merged with source and a refresh replaces it wholesale. Everything reccmp needs
beyond those raw facts is overlaid at generation time:

  1. rows at `// VTABLE:`-annotated addresses are dropped — the C++ vtable
     emission owns those addresses, and a raw `'vftable'` row at one breaks
     reccmp's vtable pairing (the old curated-merge step did this; now it is a
     generation-time overlay, not a mutation of the committed file);
  2. `config/reviewed_library_identities.csv` rows overlay name/symbol/prototype
     (prototype only when reviewed non-empty) and add rows the inventory lacks —
     reviewed identity beats the advisory export;
  3. (extension point) marker-claimed addresses can take source-derived
     names/prototypes as the declaration parser grows.

Output: <gen-dir>/symbols.csv — a disposable build artifact, regenerated by
`just generate` (inside `just build`) and consumed via reccmp-project.yml.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from tools.common.file_scan import iter_files, is_generated_source_path
from tools.common.pipe_csv import read_pipe_table
from tools.ghidra.merge_curated_symbols import write_symbols_csv
from tools.common.repo import repo_root_from_file, resolve_repo_path

DEFAULT_INVENTORY = "config/original_entities.csv"
DEFAULT_REVIEWED = "config/reviewed_library_identities.csv"
DEFAULT_GEN_DIR = "build-msvc500/generated"

_VTABLE_RE = re.compile(r"//\s*VTABLE\s*:\s*(\w+)\s+(?:0x)?([0-9a-fA-F]+)", re.IGNORECASE)


def source_vtable_addresses(repo_root: Path, target: str) -> set[int]:
    out: set[int] = set()
    for path in iter_files([str(repo_root / "src"), str(repo_root / "include")]):
        if is_generated_source_path(path):
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        for m in _VTABLE_RE.finditer(text):
            if m.group(1).upper() == target.upper():
                out.add(int(m.group(2), 16))
    return out


def load_reviewed(repo_root: Path) -> dict[int, dict]:
    path = repo_root / DEFAULT_REVIEWED
    out: dict[int, dict] = {}
    if not path.is_file():
        return out
    _fields, rows = read_pipe_table(path)
    for row in rows:
        try:
            out[int((row.get("address") or "").strip(), 16)] = row
        except ValueError:
            continue
    return out


def generate(repo_root: Path, target: str, inventory: str, gen_dir: Path) -> Path:
    inv_path = resolve_repo_path(repo_root, inventory)
    if not inv_path.is_file():
        raise SystemExit(f"Missing raw inventory: {inv_path}")
    fieldnames, rows = read_pipe_table(inv_path)
    vtables = source_vtable_addresses(repo_root, target)
    reviewed = load_reviewed(repo_root)

    kept: list[dict] = []
    dropped = overlaid = 0
    seen: set[int] = set()
    for row in rows:
        addr_text = (row.get("address") or "").strip()
        try:
            addr = int(addr_text, 16)
        except ValueError:
            kept.append(row)
            continue
        if addr in vtables:
            dropped += 1
            continue
        rv = reviewed.get(addr)
        if rv is not None:
            seen.add(addr)
            changed = False
            for src_key, dst_key in (("name", "name"), ("symbol", "symbol"),
                                     ("prototype", "prototype")):
                val = (rv.get(src_key) or "").strip()
                if val and (row.get(dst_key) or "") != val:
                    row[dst_key] = val
                    changed = True
            if (row.get("type") or "") != "function":
                row["type"] = "function"
                changed = True
            if changed:
                overlaid += 1
        kept.append(row)

    added = 0
    for addr, rv in sorted(reviewed.items()):
        if addr in seen or addr in vtables:
            continue
        kept.append({
            "address": format(addr, "x"),
            "name": (rv.get("name") or "").strip(),
            "symbol": (rv.get("symbol") or "").strip(),
            "size": "",
            "type": "function",
            "prototype": (rv.get("prototype") or "").strip(),
            "provenance": "reviewed_library_identity",
        })
        added += 1

    gen_dir.mkdir(parents=True, exist_ok=True)
    out = gen_dir / "symbols.csv"
    write_symbols_csv(out, fieldnames, kept)
    print(
        f"Wrote {out} ({len(kept)} rows; dropped {dropped} at source-VTABLE addresses; "
        f"reviewed overlay: {overlaid} updated, {added} added)"
    )
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", default="IMPERIALISM")
    parser.add_argument("--inventory", default=DEFAULT_INVENTORY)
    parser.add_argument("--gen-dir", default=DEFAULT_GEN_DIR)
    args = parser.parse_args()
    repo_root = repo_root_from_file(__file__, levels_up=1)
    generate(repo_root, args.target, args.inventory, resolve_repo_path(repo_root, args.gen_dir))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
