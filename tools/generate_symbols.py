#!/usr/bin/env python3
"""Generate the reccmp symbols table: raw inventory + source-derived overlay.

`config/original_entities.csv` is the committed raw original-binary inventory
(addresses, kinds, sizes, advisory names/prototypes from analysis). It is never
merged with source and a refresh replaces it wholesale. Everything reccmp needs
beyond those raw facts is overlaid at generation time:

  1. rows at `// VTABLE:`-annotated addresses are dropped — the C++ vtable
     emission owns those addresses, and a raw `'vftable'` row at one breaks
     reccmp's vtable pairing;
  2. `config/reviewed_library_identities.csv` rows overlay name/symbol/prototype
     (prototype only when reviewed non-empty) and add rows the inventory lacks;
  3. source-derived names/prototypes (parsed from the C++ declarations under
     markers by tools.source_model) overlay claimed addresses — a signature
     corrected in C++ mechanically reaches the generated table. Precedence:
     source declaration > reviewed identity > inventory advisory.

All facts come from tools.source_model — this module scans nothing itself.

Output: <gen-dir>/symbols.csv — a disposable build artifact, regenerated by
`just generate` (inside `just build`) and consumed via reccmp-project.yml.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from tools.common.pipe_csv import read_pipe_table
from tools.common.repo import repo_root_from_file, resolve_repo_path
from tools.ghidra.merge_curated_symbols import write_symbols_csv
from tools.source_model import build_model, reviewed_identities

DEFAULT_INVENTORY = "config/original_entities.csv"
DEFAULT_REVIEWED = "config/reviewed_library_identities.csv"
DEFAULT_GEN_DIR = "build-msvc500/generated"

def generate_rows(repo_root: Path, target: str = "IMPERIALISM",
                  inventory: str = DEFAULT_INVENTORY,
                  model=None) -> tuple[list[str], list[dict], dict]:
    """(fieldnames, rows, stats) — the overlaid symbol table, in memory."""
    inv_path = resolve_repo_path(repo_root, inventory)
    if not inv_path.is_file():
        raise SystemExit(f"Missing raw inventory: {inv_path}")
    fieldnames, rows = read_pipe_table(inv_path)
    if model is None:
        model = build_model(repo_root, target)
    vtables = model.vtables
    reviewed = {c.address: c for c in reviewed_identities(repo_root)}
    # Source-derived spellings: only FUNCTION-kind claims are name-authoritative
    # (a real parsed C++ declaration). SYNTHETIC/TEMPLATE/LIBRARY convention
    # comments often carry linker-symbol spellings and never override the
    # reviewed/inventory name.
    source_named = {a: c for a, c in model.functions.items()
                    if c.origin in ("marker", "generated")
                    and c.kind == "FUNCTION" and c.name}

    kept: list[dict] = []
    stats = {"dropped": 0, "reviewed": 0, "source": 0, "added": 0}
    seen: set[int] = set()
    for row in rows:
        addr_text = (row.get("address") or "").strip()
        try:
            addr = int(addr_text, 16)
        except ValueError:
            kept.append(row)
            continue
        if addr in vtables:
            stats["dropped"] += 1
            continue
        rv = reviewed.get(addr)
        if rv is not None:
            seen.add(addr)
            changed = False
            for val, dst_key in ((rv.name, "name"), (rv.symbol, "symbol"),
                                 (rv.prototype, "prototype")):
                if val and (row.get(dst_key) or "") != val:
                    row[dst_key] = val
                    changed = True
            if (row.get("type") or "") != "function":
                row["type"] = "function"
                changed = True
            if changed:
                stats["reviewed"] += 1
        sc = source_named.get(addr)
        if sc is not None:
            # Source declaration wins last: name always; prototype when parsed.
            changed = False
            if sc.name and (row.get("name") or "") != sc.name:
                row["name"] = sc.name
                changed = True
            if sc.prototype and (row.get("prototype") or "") != sc.prototype:
                row["prototype"] = sc.prototype
                changed = True
            if changed:
                stats["source"] += 1
        kept.append(row)

    for addr, rv in sorted(reviewed.items()):
        if addr in seen or addr in vtables:
            continue
        kept.append({
            "address": format(addr, "x"),
            "name": rv.name,
            "symbol": rv.symbol,
            "size": "",
            "type": "function",
            "prototype": rv.prototype,
            "provenance": "reviewed_library_identity",
        })
        stats["added"] += 1
    return fieldnames, kept, stats


def generate(repo_root: Path, target: str, inventory: str, gen_dir: Path) -> Path:
    fieldnames, kept, stats = generate_rows(repo_root, target, inventory)
    gen_dir.mkdir(parents=True, exist_ok=True)
    out = gen_dir / "symbols.csv"
    write_symbols_csv(out, fieldnames, kept)
    print(
        f"Wrote {out} ({len(kept)} rows; dropped {stats['dropped']} at source-VTABLE "
        f"addresses; reviewed overlay: {stats['reviewed']} updated, {stats['added']} "
        f"added; source-declaration overlay: {stats['source']} updated)"
    )
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--target", default="IMPERIALISM")
    parser.add_argument("--inventory", default=DEFAULT_INVENTORY)
    parser.add_argument("--gen-dir", default=DEFAULT_GEN_DIR)
    args = parser.parse_args()
    repo_root = repo_root_from_file(__file__, levels_up=1)
    generate(repo_root, args.target, args.inventory, resolve_repo_path(repo_root, args.gen_dir))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
