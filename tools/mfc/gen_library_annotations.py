"""Generate reccmp `// LIBRARY:` annotations for statically-linked MFC functions.

When the build links retail MFC (`nafxcw.lib`) instead of hand-rolling the MFC
classes, every MFC function lives in the recompiled binary at byte-identical code
(verified: CObject::IsKindOf matches the original opcode-for-opcode). reccmp pairs
such functions when an original address is annotated `// LIBRARY:` followed by the
qualified symbol name; the marker is scanned from comments even inside `#if 0`, so
the generated header compiles to nothing.

Usage:
    uv run python -m tools.mfc.gen_library_annotations \
        --symbols config/symbols.csv --target IMPERIALISM \
        --out include/game/library_mfc.h

Filtering is by leading class name (CObject::, CString::, ...). Extend MFC_CLASSES
as more of the MFC surface is reclaimed from the library.
"""

from __future__ import annotations

import argparse
import csv
import sys

MFC_CLASSES = (
    "CObject", "CRuntimeClass", "CString", "CPtrList", "CPtrArray", "CObList",
    "CList", "CArchive", "CArchiveException", "CMapPtrToPtr", "CMapStringToPtr",
    "CException", "CFile", "CFileException", "CMemFile", "CStdioFile", "CDumpContext",
    "CCmdTarget", "CWnd", "CWinApp", "CWinThread", "CDialog", "CDocument", "CView",
    "CFrameWnd", "CGdiObject", "CDC", "CClientDC", "CPaintDC", "CBrush", "CPen",
    "CFont", "CBitmap", "CPalette", "CRgn", "CMenu", "CTime", "CTimeSpan",
)


def is_mfc(name: str) -> bool:
    cls = name.split("::", 1)[0]
    return cls in MFC_CLASSES and "::" in name


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--symbols", default="config/symbols.csv")
    ap.add_argument("--target", default="IMPERIALISM")
    ap.add_argument("--out", default="include/game/library_mfc.h")
    args = ap.parse_args(argv)

    rows: list[tuple[str, str]] = []
    with open(args.symbols, newline="") as fh:
        for line in fh:
            parts = line.rstrip("\n").split("|")
            if len(parts) < 4 or parts[3] != "function":
                continue
            addr, name = parts[0], parts[1]
            if is_mfc(name):
                rows.append((addr, name))

    rows.sort(key=lambda r: int(r[0], 16))

    out = [
        "#pragma once",
        "// AUTO-GENERATED by tools/mfc/gen_library_annotations.py — do not hand-edit.",
        "// reccmp LIBRARY annotations for statically-linked retail MFC (nafxcw.lib).",
        "// Compiles to nothing; the markers are read from comments by reccmp's parser.",
        "#if 0",
    ]
    for addr, name in rows:
        out.append(f"// LIBRARY: {args.target} 0x{int(addr,16):08x}")
        out.append(f"// {name}")
        out.append("")
    out.append("#endif")
    text = "\n".join(out) + "\n"

    with open(args.out, "w") as fh:
        fh.write(text)
    print(f"Wrote {len(rows)} LIBRARY annotations to {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
